def predict_student_outcome(student_dict):
    """
    Takes a dictionary of student details and returns:
    - placement prediction (Placed / Not Placed)
    - placement probability
    - predicted salary (only if placed)
    """
    # Convert input into a one-row DataFrame
    new_df = pd.DataFrame([student_dict])

    # One-hot encode the same way as training data
    new_df_encoded = pd.get_dummies(new_df, columns=categorical_cols)

    # --- Placement prediction ---
    # Align columns with training data (fill missing dummy columns with 0)
    new_df_placement = new_df_encoded.reindex(columns=X_placement.columns, fill_value=0)

    placement_pred = placement_model.predict(new_df_placement)[0]
    placement_proba = placement_model.predict_proba(new_df_placement)[0][1]  # probability of "Placed"

    result = {
        "placement_prediction": "Placed" if placement_pred == 1 else "Not Placed",
        "placement_probability": round(placement_proba * 100, 2)
    }

    # --- Salary prediction (only if placed) ---
    if placement_pred == 1:
        new_df_salary = new_df_encoded.reindex(columns=X_salary.columns, fill_value=0)
        salary_pred = salary_model.predict(new_df_salary)[0]
        result["predicted_salary"] = round(salary_pred, 2)
    else:
        result["predicted_salary"] = None

    return result

