import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.metrics import (
    accuracy_score, classification_report, ConfusionMatrixDisplay,
    mean_absolute_error, r2_score
)

RANDOM_STATE = 42
sns.set_theme(style="whitegrid", palette="Set2")

# Encode target for classification: Placed = 1, Not Placed = 0
df["placement_label"] = df["placement_status"].map({"Placed": 1, "Not Placed": 0})

# Salary subset: only students who were actually placed
df_placed = df[df["placement_status"] == "Placed"].copy()

print("Full dataset shape:", df.shape)
print("Placed-only subset shape:", df_placed.shape)

categorical_cols = ["college_tier", "country", "university_ranking_band", "specialization", "industry"]

df_encoded = pd.get_dummies(df, columns=categorical_cols, drop_first=True)
df_placed_encoded = pd.get_dummies(df_placed, columns=categorical_cols, drop_first=True)

print(df_encoded.shape)
print(df_placed_encoded.columns.tolist())

# Features for placement model: drop the raw text status, the label, and salary
# (salary would leak information about placement, so it must NOT be a feature here)
X_placement = df_encoded.drop(columns=["placement_status", "placement_label", "salary"])
y_placement = df_encoded["placement_label"]

X_train, X_test, y_train, y_test = train_test_split(
    X_placement, y_placement, test_size=0.2, random_state=RANDOM_STATE, stratify=y_placement
)

print("Train shape:", X_train.shape)
print("Test shape:", X_test.shape)

placement_model = RandomForestClassifier(
    n_estimators=200,
    random_state=RANDOM_STATE,
    n_jobs=-1
)

placement_model.fit(X_train, y_train)

placement_predictions = placement_model.predict(X_test)
placement_accuracy = accuracy_score(y_test, placement_predictions)

print(f"Placement model accuracy: {placement_accuracy:.2%}")

# Baseline: what if the model just always guessed the majority class?
baseline_accuracy = max(y_test.mean(), 1 - y_test.mean())
print(f"Baseline (always guess majority class): {baseline_accuracy:.2%}")

print("\nClassification Report:")
print(classification_report(y_test, placement_predictions))

fig, ax = plt.subplots(figsize=(6, 6))

ConfusionMatrixDisplay.from_predictions(
    y_test,
    placement_predictions,
    display_labels=["Not Placed", "Placed"],
    cmap="Blues",
    colorbar=False,
    ax=ax
)

ax.set_title("Confusion Matrix — Placement Model")
plt.tight_layout()
plt.show()

